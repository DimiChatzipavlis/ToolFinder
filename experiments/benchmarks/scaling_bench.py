"""Flat vs HNSW scaling benchmark: where does approximate search actually pay?

Measures, for catalog sizes N in {15, 100, 1000, 10000} with schema-derived
embeddings and N=100000 with random unit vectors (latency-only tier):

  - index build time and serialized size
  - search-only latency per query (p50/p95, single FAISS thread)
  - HNSW recall@10 against exact flat ground truth (M x efSearch sweep)

plus the query *encoding* cost (the part the index can never remove), so the
report can show what fraction of routing latency retrieval actually is.

Synthetic schemas are generated by recombining vocabulary from the 30 real
GitHub schemas (verb x noun x qualifier names, templated descriptions, sampled
parameters). They are distribution-plausible stand-ins, not real tools; the
report labels them as such.

Usage:
    python experiments/benchmarks/scaling_bench.py
"""

from __future__ import annotations

import itertools
import json
import random
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from experiments import paths  # noqa: E402
from experiments.representation import represent_raw  # noqa: E402

SCHEMA_SIZES = (15, 100, 1_000, 10_000)
RANDOM_SIZES = (100_000,)
HNSW_M_VALUES = (16, 32)
EF_SEARCH_VALUES = (16, 64, 128, 256)
TOP_K = 10
EMBED_MODEL = "sentence-transformers/all-mpnet-base-v2"

VERBS = ["create", "get", "list", "update", "delete", "search", "merge", "fork", "assign", "add", "remove", "publish", "archive", "sync"]
NOUNS = ["branch", "issue", "commit", "file", "release", "tag", "label", "team", "repository", "pull_request", "comment", "workflow", "milestone", "deployment", "webhook", "artifact", "package", "secret", "environment", "review"]
QUALIFIERS = ["", "_by_id", "_for_user", "_in_org", "_batch", "_async", "_v2", "_metadata", "_history", "_summary"]
PARAM_NAMES = ["owner", "repo", "name", "title", "body", "state", "page", "per_page", "ref", "sha", "path", "labels", "assignee", "sort", "direction", "since", "until", "query"]
DESCRIPTION_TEMPLATES = [
    "{verb_cap} a {noun_text} in a GitHub repository. Use this to {verb} the {noun_text} and inspect its metadata.",
    "{verb_cap} {noun_text} records across repositories with filtering and pagination support.",
    "Tool for {verb}ing the {noun_text} of a project. Returns structured {noun_text} data for downstream automation.",
    "{verb_cap} the specified {noun_text}. Supports advanced options for batch operations and metadata control.",
]


def generate_synthetic_schemas(count: int, seed: int = 7) -> list[str]:
    rng = random.Random(seed)
    names = [
        f"{verb}_{noun}{qualifier}"
        for verb, noun, qualifier in itertools.product(VERBS, NOUNS, QUALIFIERS)
    ]
    rng.shuffle(names)
    if count > len(names):
        names = [f"{name}_{i}" for i, name in enumerate(itertools.islice(itertools.cycle(names), count))]
    schemas: list[str] = []
    for name in names[:count]:
        verb, noun = name.split("_")[0], name.split("_")[1]
        template = rng.choice(DESCRIPTION_TEMPLATES)
        description = template.format(verb=verb, verb_cap=verb.capitalize(), noun_text=noun.replace("_", " "))
        params = rng.sample(PARAM_NAMES, k=rng.randint(2, 6))
        schema = {
            "name": name,
            "description": description,
            "inputSchema": {
                "type": "object",
                "properties": {param: {"type": "string", "description": f"The {param} value"} for param in params},
                "required": params[:2],
            },
        }
        schemas.append(represent_raw(schema))
    return schemas


def embed_texts(texts: list[str]) -> np.ndarray:
    import faiss
    import torch
    from sentence_transformers import SentenceTransformer

    device = "cuda" if torch.cuda.is_available() else "cpu"
    model = SentenceTransformer(EMBED_MODEL, device=device)
    embeddings = model.encode(texts, batch_size=64, convert_to_numpy=True, show_progress_bar=False)
    embeddings = np.asarray(embeddings, dtype=np.float32)
    faiss.normalize_L2(embeddings)
    return embeddings


def measure_encoder_latency() -> dict:
    """Single-query encode latency, the floor no index choice can remove."""
    import torch
    from sentence_transformers import SentenceTransformer

    sample = "Create a pull request to merge the auth cleanup changes."
    results = {}
    devices = ["cpu"] + (["cuda"] if torch.cuda.is_available() else [])
    for device in devices:
        model = SentenceTransformer(EMBED_MODEL, device=device)
        model.encode([sample])  # warmup
        timings = []
        for _ in range(50):
            start = time.perf_counter()
            model.encode([sample], show_progress_bar=False)
            timings.append((time.perf_counter() - start) * 1000.0)
        results[device] = {
            "p50_ms": round(float(np.percentile(timings, 50)), 2),
            "p95_ms": round(float(np.percentile(timings, 95)), 2),
        }
        del model
    return results


def search_latency(index, query_vectors: np.ndarray, k: int, min_measurements: int = 1000) -> dict:
    repeats = max(1, min_measurements // len(query_vectors))
    timings = []
    for _ in range(repeats):
        for i in range(len(query_vectors)):
            query = query_vectors[i : i + 1]
            start = time.perf_counter()
            index.search(query, k)
            timings.append((time.perf_counter() - start) * 1000.0)
    return {
        "p50_ms": round(float(np.percentile(timings, 50)), 4),
        "p95_ms": round(float(np.percentile(timings, 95)), 4),
        "n_measurements": len(timings),
    }


def bench_tier(corpus_vectors: np.ndarray, query_vectors: np.ndarray, tier_label: str) -> dict:
    import faiss

    faiss.omp_set_num_threads(1)
    dim = corpus_vectors.shape[1]
    n = corpus_vectors.shape[0]
    tier: dict = {"n": n, "dim": dim, "tier": tier_label, "indexes": {}}

    flat = faiss.IndexFlatIP(dim)
    started = time.perf_counter()
    flat.add(corpus_vectors)
    flat_build_s = time.perf_counter() - started
    _, ground_truth = flat.search(query_vectors, TOP_K)
    tier["indexes"]["flat"] = {
        "build_s": round(flat_build_s, 4),
        "size_bytes": len(faiss.serialize_index(flat)),
        "latency": search_latency(flat, query_vectors, TOP_K),
        "recall@10_vs_exact": 1.0,
    }

    for m in HNSW_M_VALUES:
        hnsw = faiss.IndexHNSWFlat(dim, m, faiss.METRIC_INNER_PRODUCT)
        started = time.perf_counter()
        hnsw.add(corpus_vectors)
        build_s = time.perf_counter() - started
        for ef_search in EF_SEARCH_VALUES:
            hnsw.hnsw.efSearch = ef_search
            _, approx = hnsw.search(query_vectors, TOP_K)
            recall = float(
                np.mean(
                    [
                        len(set(approx_row.tolist()) & set(truth_row.tolist())) / TOP_K
                        for approx_row, truth_row in zip(approx, ground_truth)
                    ]
                )
            )
            tier["indexes"][f"hnsw_m{m}_ef{ef_search}"] = {
                "build_s": round(build_s, 4),
                "size_bytes": len(faiss.serialize_index(hnsw)),
                "latency": search_latency(hnsw, query_vectors, TOP_K),
                "recall@10_vs_exact": round(recall, 4),
            }
    return tier


def main() -> None:
    import pandas as pd

    paths.ensure_dirs()
    rng = np.random.default_rng(7)

    print("[encode] real + synthetic schema corpora")
    corpus = json.loads(paths.CORPUS_JSON.read_text(encoding="utf-8"))
    real_texts = [represent_raw(entry["schema"]) for entry in corpus.values()]
    synthetic_texts = generate_synthetic_schemas(max(SCHEMA_SIZES) - len(real_texts))
    all_texts = real_texts + synthetic_texts
    corpus_vectors = embed_texts(all_texts)

    queries = pd.read_csv(paths.QUERIES_CSV)
    query_vectors = embed_texts(queries[queries["dataset"] == "v2"]["anchor"].tolist())

    output: dict = {
        "embed_model": EMBED_MODEL,
        "top_k": TOP_K,
        "faiss_threads": 1,
        "encoder_latency": measure_encoder_latency(),
        "tiers": [],
    }
    print(f"[encoder] single-query encode: {output['encoder_latency']}")

    for n in SCHEMA_SIZES:
        print(f"[tier] N={n} (schema embeddings)")
        output["tiers"].append(bench_tier(corpus_vectors[:n], query_vectors, "schema"))

    for n in RANDOM_SIZES:
        print(f"[tier] N={n} (random unit vectors, latency-only distribution)")
        random_corpus = rng.standard_normal((n, corpus_vectors.shape[1])).astype(np.float32)
        random_corpus /= np.linalg.norm(random_corpus, axis=1, keepdims=True)
        output["tiers"].append(bench_tier(random_corpus, query_vectors, "random"))

    out_path = paths.RESULTS_DIR / "scaling_bench.json"
    out_path.write_text(json.dumps(output, indent=1), encoding="utf-8")
    print(f"\nwrote {out_path}")

    for tier in output["tiers"]:
        flat_latency = tier["indexes"]["flat"]["latency"]["p50_ms"]
        hnsw_key = "hnsw_m32_ef64"
        hnsw_latency = tier["indexes"][hnsw_key]["latency"]["p50_ms"]
        hnsw_recall = tier["indexes"][hnsw_key]["recall@10_vs_exact"]
        print(
            f"N={tier['n']:>6} ({tier['tier']}): flat p50={flat_latency:.4f}ms exact | "
            f"{hnsw_key} p50={hnsw_latency:.4f}ms recall@10={hnsw_recall:.4f}"
        )


if __name__ == "__main__":
    main()
